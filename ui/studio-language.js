// Normalize English source labels too, so both directions work on newly rendered views.
const vietnameseLabels = Object.fromEntries(Object.entries(studioTranslations).map(([vi,en])=>[en,vi]));
function vietnameseText(text) {
    return vietnameseLabels[text] || text;
}
function localizedText(text, en) {
    const trimmed = text.trim();
    const canonical = vietnameseText(trimmed);
    const translated = en ? englishText(canonical) : canonical;
    return text.replace(trimmed, translated);
}
const originals = new WeakMap();
function englishText(text) {
    if (studioTranslations[text]) return studioTranslations[text];
    // Labels can include a decorative arrow and non-breaking spaces.
    const decorated = text.match(/^(.*?)[\s\u00a0]+([↗＋▾])$/);
    if (decorated) return englishText(decorated[1].trim()) + ' ' + decorated[2];
    let result = studioTranslations[text];
    if (result) return result;
    const affixes = [
        ['Gốc · ','Factory · '],['Đồ thị tham khảo · ','Reference curve · '],
        [' · bản nháp từ FiiO',' · draft from FiiO'],[' · bản nháp',' · draft'],
        [' preset trong thư viện FiiO',' presets in your FiiO library'],
        ['Cấu hình phải có đủ 5 band','Configuration must contain 5 bands'],
        ['Không lưu được cài đặt.','Could not save settings.']
    ];
    result = text;
    for (const [vi,en] of affixes) result = result.replace(vi,en);
    return result;
}
function localizeStudio() {
    const en = document.documentElement.lang === 'en';
    const walk = document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
    while(walk.nextNode()) {
        const node=walk.currentNode, parent=node.parentElement;
        if(!parent || parent.closest('script,style,[translate="no"],textarea,option')) continue;
        const value=node.nodeValue, memo=originals.get(node);
        const original=memo && memo.rendered===value ? memo.original : value;
        const trimmed=original.trim();
        const rendered=localizedText(original,en);
        originals.set(node,{original,rendered});
        if(value!==rendered)node.nodeValue=rendered;
    }
    for(const el of document.querySelectorAll('[placeholder],[title],[aria-label]')) {
        if(el.closest('[translate="no"]'))continue;
        for(const attribute of ['placeholder','title','aria-label']) {
            if(!el.hasAttribute(attribute))continue;
            const key='i18n'+attribute, value=el.getAttribute(attribute);
            const memo=el[key], original=memo && memo.rendered===value ? memo.original : value;
            const rendered=localizedText(original,en);
            el[key]={original,rendered};
            if(value!==rendered)el.setAttribute(attribute,rendered);
        }
    }
}
let languageFrame;
new MutationObserver(()=> {
    if(languageFrame)return;
    languageFrame=requestAnimationFrame(()=>{languageFrame=0;localizeStudio();});
}).observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['title','placeholder','aria-label']});
localizeStudio();
